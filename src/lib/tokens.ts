import "server-only";

import { randomBytes } from "node:crypto";

// Токен ссылки — единственное, что защищает витрину: кто знает ссылку, тот
// и внутри. Поэтому он должен быть непредсказуемым. 16 случайных байт —
// это 2^128 вариантов, перебрать нельзя. Math.random() здесь недопустим:
// он предсказуем, и по одной выданной ссылке можно было бы вычислить другие.
//
// Общий модуль, а не локальная функция в actions/share-links.ts: токен
// нужен и там (ручная выдача ссылки), и в actions/hubs.ts (автосоздание
// ссылки «Для АМО» при создании/копировании хаба).
export function newShareToken(): string {
  return randomBytes(16).toString("base64url");
}
