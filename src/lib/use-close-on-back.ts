"use client";

import { useEffect } from "react";

/**
 * Открытие полноэкранного окна кладёт лишнюю запись в историю; в
 * установленном PWA (display: standalone) аппаратная/жестовая кнопка «назад»
 * на Android двигает именно эту историю, а не выходит из приложения — здесь
 * мы это ловим и закрываем окно вместо него.
 *
 * Компонент, который вызывает хук, должен существовать только пока окно
 * открыто (монтироваться/размонтироваться целиком) — тогда cleanup сработает
 * и при закрытии кнопкой «назад», и при закрытии любым другим способом.
 */
export function useCloseOnBack(onClose: () => void) {
  useEffect(() => {
    // Кладём новую запись, только если наверху истории ещё не наша: React
    // StrictMode в dev вызывает эффект дважды подряд (mount → cleanup →
    // mount) на одном и том же экземпляре компонента — без проверки второй
    // вызов продублировал бы запись.
    const state = window.history.state as { __overlay?: boolean } | null;
    if (!state?.__overlay) {
      window.history.pushState({ __overlay: true }, "");
    }

    const onPopState = () => onClose();
    window.addEventListener("popstate", onPopState);

    // При закрытии не кнопкой «назад» (крестик/Escape/выбор результата) свою
    // запись истории НЕ трогаем — раньше здесь стоял history.back(), чтобы
    // убрать её сразу, но это асинхронный вызов: он может исполниться уже
    // после того, как что-то ещё успело подвинуть историю (например, сам
    // Next.js router при обычной навигации), и тогда откатывал не на одну
    // запись назад, а мимо — пользователя закидывало на случайную более
    // раннюю страницу. Оставленная запись почти не заметна: адрес у нашей
    // записи такой же, как у страницы под ней, так что случайное «назад»
    // после закрытия один раз просто ничего не покажет, а не улетит не туда.
    return () => {
      window.removeEventListener("popstate", onPopState);
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);
}
